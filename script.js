function showRedeemMessage(
  message,
  type = "normal"
) {

  const messageElement =
    document.getElementById(
      "redeemCodeMessage"
    );


  if (!messageElement) {
    return;
  }


  messageElement.textContent =
    message;


  messageElement.classList.remove(
    "success",
    "error"
  );


  if (
    type === "success"
  ) {

    messageElement.classList.add(
      "success"
    );

  }


  if (
    type === "error"
  ) {

    messageElement.classList.add(
      "error"
    );

  }

}


// =========================================================
// REDEEM CODE
// =========================================================

function redeemAssetHubCode() {

  const input =
    document.getElementById(
      "redeemCodeInput"
    );


  if (!input) {
    return;
  }


  const code =
    input.value
      .trim()
      .toUpperCase();


  if (!code) {

    showRedeemMessage(
      "Enter a code first.",
      "error"
    );

    return;
  }


  const reward =
    redeemCodes[
      code
    ];


  // INVALID CODE

  if (!reward) {

    showRedeemMessage(
      "That code is invalid.",
      "error"
    );

    return;
  }


  // ALREADY REDEEMED

  if (
    redeemedCodes.includes(
      code
    )
  ) {

    showRedeemMessage(
      "You already redeemed this code.",
      "error"
    );

    return;
  }


  // =====================================================
  // GIVE COINS
  // =====================================================

  themeStoreData.coins +=
    reward.coins;


  // SAVE COINS

  saveThemeStoreData();


  // SAVE CODE AS USED

  redeemedCodes.push(
    code
  );


  saveRedeemedCodes();


  // REFRESH STORE COINS

  renderThemeStore();


  // CLEAR INPUT

  input.value =
    "";


  // SUCCESS

  showRedeemMessage(
    reward.message,
    "success"
  );

}


