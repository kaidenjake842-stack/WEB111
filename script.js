function loadRedeemedCodes() {

  try {

    const saved =
      JSON.parse(
        localStorage.getItem(
          REDEEM_CODES_KEY
        )
      );


    return Array.isArray(saved)
      ? saved
      : [];


  } catch {

    return [];

  }

}


