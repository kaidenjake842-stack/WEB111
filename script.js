// OPEN LESSON
// Supports unlimited code blocks through lesson.codes[]
// Old lessons using lesson.code still work
// =========================================================

function openLesson(id) {

  const lesson =
    lessons.find(
      item => item.id === id
    );

  if (!lesson) {
    return;
  }

  const modal =
    document.getElementById(
      "lessonModal"
    );

  if (!modal) {
    return;
  }

  const meta =
    document.getElementById(
      "lessonModalMeta"
    );

  const title =
    document.getElementById(
      "lessonModalTitle"
    );

  const summary =
    document.getElementById(
      "lessonModalSummary"
    );

  const content =
    document.getElementById(
      "lessonModalContent"
    );

  const codeList =
    document.getElementById(
      "lessonCodeList"
    );


  // =====================================================
  // META
  // =====================================================

  if (meta) {

    meta.innerHTML = `
      <span class="pill">
        ${lesson.category || "Lesson"}
      </span>

      ${
        lesson.difficulty
          ? `<span class="pill">${lesson.difficulty}</span>`
          : ""
      }

      ${
        lesson.minutes
          ? `<span class="pill">${lesson.minutes} MIN</span>`
          : ""
      }
    `;

  }


  // =====================================================
  // LESSON CONTENT
  // =====================================================

  if (title) {
    title.textContent =
      lesson.title || "Lesson";
  }

  if (summary) {
    summary.textContent =
      lesson.summary || "";
  }

  if (content) {
    content.textContent =
      lesson.content || "";
  }


  // =====================================================
  // UNLIMITED CODE BLOCKS
  // =====================================================

  if (codeList) {

    codeList.innerHTML = "";

    let examples = [];

    // New unlimited system.
    if (Array.isArray(lesson.codes)) {
      examples =
        lesson.codes;
    }

    // Backwards compatibility for existing lessons.
    else if (lesson.code) {
      examples = [
        {
          title: "Example Code",
          language: "lua",
          code: lesson.code
        }
      ];
    }

    examples.forEach(
      (example, index) => {

        const wrapper =
          document.createElement(
            "div"
          );

        wrapper.className =
          "code-block";


        // Header
        const head =
          document.createElement(
            "div"
          );

        head.className =
          "code-head";


        const info =
          document.createElement(
            "div"
          );


        const heading =
          document.createElement(
            "strong"
          );

        heading.textContent =
          example.title ||
          `Code Example ${index + 1}`;

        info.appendChild(
          heading
        );


        // Language badge
        if (example.language) {

          const language =
            document.createElement(
              "span"
            );

          language.className =
            "code-language";

          language.textContent =
            example.language;

          info.appendChild(
            language
          );

        }


        // Copy button
        const copyButton =
          document.createElement(
            "button"
          );

        copyButton.className =
          "small-button copy-code-button";

        copyButton.type =
          "button";

        copyButton.textContent =
          "Copy Code";

        copyButton.addEventListener(
          "click",
          () => {

            copyLessonCode(
              example.code || "",
              copyButton
            );

          }
        );


        head.appendChild(
          info
        );

        head.appendChild(
          copyButton
        );


        // Code body
        const pre =
          document.createElement(
            "pre"
          );

        const code =
          document.createElement(
            "code"
          );

        code.textContent =
          example.code || "";

        pre.appendChild(
          code
        );


        wrapper.appendChild(
          head
        );

        wrapper.appendChild(
          pre
        );

        codeList.appendChild(
          wrapper
        );

      }
    );

  }


  // =====================================================
  // SHOW MODAL
  // =====================================================

  modal.classList.remove(
    "hidden"
  );

  document.body.style.overflow =
    "hidden";

}

window.openLesson =
  openLesson;


// =========================================================
// COPY ANY LESSON CODE BLOCK
// =========================================================

async function copyLessonCode(
  code,
  button
) {

  if (!code) {
    return;
  }

  const originalText =
    button?.textContent ||
    "Copy Code";

  try {

    await navigator
      .clipboard
      .writeText(
        code
      );

    if (button) {
      button.textContent =
        "Copied! ✓";
    }

  } catch (error) {

    console.error(
      "Clipboard API failed:",
      error
    );

    // Fallback for browsers where navigator.clipboard is blocked.
    const textarea =
      document.createElement(
        "textarea"
      );

    textarea.value =
      code;

    textarea.style.position =
      "fixed";

    textarea.style.opacity =
      "0";

    document.body.appendChild(
      textarea
    );

    textarea.select();

    try {

      document.execCommand(
        "copy"
      );

      if (button) {
        button.textContent =
          "Copied! ✓";
      }

    } catch {

      if (button) {
        button.textContent =
          "Copy Failed";
      }

    }

    textarea.remove();

  }

  setTimeout(
    () => {

      if (button) {
        button.textContent =
          originalText;
      }

    },
    1500
  );

}

window.copyLessonCode =
  copyLessonCode;


