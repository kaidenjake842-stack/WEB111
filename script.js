// =========================================================
// SECONDARY ACCENT
// =========================================================

function makeSecondaryAccent(
  hex
) {

  const raw =
    hex.replace(
      "#",
      ""
    );


  if (
    raw.length !== 6
  ) {

    return "#7768ff";

  }


  const r =
    parseInt(
      raw.slice(
        0,
        2
      ),
      16
    );


  const g =
    parseInt(
      raw.slice(
        2,
        4
      ),
      16
    );


  const b =
    parseInt(
      raw.slice(
        4,
        6
      ),
      16
    );


  return `rgb(
    ${
      Math.min(
        255,
        Math.round(
          r * 0.72 + 70
        )
      )
    },
    ${
      Math.min(
        255,
        Math.round(
          g * 0.72 + 40
        )
      )
    },
    ${
      Math.min(
        255,
        Math.round(
          b * 0.72 + 95
        )
      )
    }
  )`;

}




// =========================================================
// APPLY THEME
// =========================================================

function applyTheme() {

  document.body
    .classList.remove(

      "theme-dark",

      "theme-midnight",

      "theme-light",

      "glow-off",

      "animations-off"

    );


  document.body
    .classList.add(

      `theme-${themeSettings.theme}`

    );


  if (
    !themeSettings.glow
  ) {

    document.body
      .classList.add(
        "glow-off"
      );

  }


  if (
    !themeSettings.animations
  ) {

    document.body
      .classList.add(
        "animations-off"
      );

  }


  document
    .documentElement
    .style
    .setProperty(

      "--primary",

      themeSettings.accent

    );


  document
    .documentElement
    .style
    .setProperty(

      "--primary2",

      makeSecondaryAccent(
        themeSettings.accent
      )

    );


  const picker =
    document.getElementById(
      "customAccent"
    );


  const glow =
    document.getElementById(
      "glowToggle"
    );


  const animations =
    document.getElementById(
      "animationToggle"
    );


  if (picker) {

    picker.value =
      themeSettings.accent;

  }


  if (glow) {

    glow.checked =
      themeSettings.glow;

  }


  if (animations) {

    animations.checked =
      themeSettings.animations;

  }


  document
    .querySelectorAll(
      ".theme-choice"
    )
    .forEach(button => {

      button
        .classList
        .toggle(

          "active",

          button.dataset.theme ===
            themeSettings.theme

        );

    });


  document
    .querySelectorAll(
      ".accent-dot"
    )
    .forEach(button => {

      const color =
        button.dataset.accent ||
        "";


      button
        .classList
        .toggle(

          "active",

          color
            .toLowerCase() ===

            themeSettings
              .accent
              .toLowerCase()

        );

    });

}


