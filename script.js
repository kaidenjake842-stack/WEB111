// =========================================================

function equipStoreTheme(
  themeId
) {

  const theme =
    storeThemes.find(
      item =>
        item.id ===
        themeId
    );


  if (!theme) {
    return;
  }


  if (
    !themeStoreData
      .owned
      .includes(
        themeId
      )
  ) {

    return;

  }


  themeStoreData.equipped =
    themeId;


  saveThemeStoreData();


  // Use your existing
  // Asset Hub theme system

  themeSettings.theme =
    theme.theme;


  themeSettings.accent =
    theme.accent;


  applyTheme();

  saveTheme();


  renderThemeStore();

}


window.equipStoreTheme =
  equipStoreTheme;


// =========================================================
// PURCHASE THEME
// =========================================================

function buyStoreTheme(
  themeId
) {

  const theme =
    storeThemes.find(
      item =>
        item.id ===
        themeId
    );


  if (!theme) {
    return;
  }


  // Already owned

  if (
    themeStoreData
      .owned
      .includes(
        themeId
      )
  ) {

    equipStoreTheme(
      themeId
    );

    return;

  }


  // Not enough coins

  if (
    themeStoreData.coins <
    theme.price
  ) {

    alert(
      "You do not have enough Asset Hub Coins for this theme."
    );

    return;

  }


  // Remove coins

  themeStoreData.coins -=
    theme.price;


  // Add ownership

  themeStoreData
    .owned
    .push(
      themeId
    );


  themeStoreData.equipped =
    themeId;


  saveThemeStoreData();


  equipStoreTheme(
    themeId
  );

}


window.buyStoreTheme =
  buyStoreTheme;


