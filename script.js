// =========================================================
// COUNTDOWN HELPERS
// =========================================================

function getCountdown(
  targetTime
) {

  const difference =
    Math.max(
      0,
      targetTime -
        Date.now()
    );


  return {

    released:
      difference <= 0,


    days:
      Math.floor(
        difference /
        86400000
      ),


    hours:
      Math.floor(
        (
          difference %
          86400000
        ) /
        3600000
      ),


    minutes:
      Math.floor(
        (
          difference %
          3600000
        ) /
        60000
      ),


    seconds:
      Math.floor(
        (
          difference %
          60000
        ) /
        1000
      )

  };

}


