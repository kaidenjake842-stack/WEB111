function loadThemeStoreData() {

  try {

    const saved =
      JSON.parse(
        localStorage.getItem(
          THEME_STORE_KEY
        )
      );


    return {

      coins:
        Number(
          saved?.coins
        ) || 0,


      owned:
        Array.isArray(
          saved?.owned
        )

          ? saved.owned

          : [
              "default-blue"
            ],


      equipped:
        saved?.equipped ||
        "default-blue",

      claimedStarterCoins:
        saved?.claimedStarterCoins === true

    };


  } catch {

    return {

      coins:
        0,

      owned: [
        "default-blue"
      ],

      equipped:
        "default-blue",

      claimedStarterCoins:
        false

    };

  }

}


